"""Resolve the ECLIPSE preset against both verified Motor executables, offline.

Usage: python tools/generate-low-performance.py path/to/candidate.cfg
Requires the same pefile dependency as the existing offline inspection tools.
"""
import hashlib
import json
import pathlib
import re
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools/python-deps'))
import pefile
import capstone

def resolve(path, expected_hash, names):
    data = path.read_bytes()
    assert hashlib.sha256(data).hexdigest() == expected_hash, 'Unknown executable'
    pe = pefile.PE(data=data, fast_load=True)
    mem = pe.get_memory_mapped_image()
    section = next(s for s in pe.sections if s.Name.rstrip(b'\0') == b'.text')
    start = section.VirtualAddress
    code = mem[start:start + section.Misc_VirtualSize]
    signature = bytes.fromhex('48 89 5c 24 10 57 48 83 ec 20 48 8b fa 48 8b d9 45 84 c0 75 7f 48 8b 11 8b 42 40 0f ba e0 0e 73 1d')
    hits = [m.start() + start for m in re.finditer(re.escape(signature), code)]
    assert len(hits) == 1, 'CVar setter is not unique'
    setter = hits[0]
    assert mem[setter+0x3e:setter+0x44] == bytes.fromhex('0f ba e0 0f 73 1d')
    result = {}
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_64)
    md.detail = True
    for m in re.finditer(b'\x48\x8d\x05', code):
        at = start + m.start()
        dest = at + 7 + struct.unpack_from('<i', mem, at+3)[0]
        if not 0 <= dest < len(mem):
            continue
        name = mem[dest:dest+120].split(bytes([0]), 1)[0].decode('ascii', errors='replace')
        if name not in names:
            continue
        for ins in list(md.disasm(mem[at:at+65], at))[1:]:
            if (ins.mnemonic == 'mov' and ins.operands[0].type == capstone.x86.X86_OP_MEM
                    and ins.operands[0].mem.base == capstone.x86.X86_REG_RIP
                    and ins.operands[1].type == capstone.x86.X86_OP_REG
                    and ins.operands[1].reg == capstone.x86.X86_REG_RAX):
                wrapper = ins.address + ins.size + ins.disp - 0x30
                assert name not in result, 'Ambiguous registration: ' + name
                result[name] = wrapper
                break
    return setter, result, mem

def main():
    source = pathlib.Path(sys.argv[1]).read_text(encoding='utf-8-sig')
    rows = re.findall(r'^([A-Za-z0-9_]+)\s+"([^"]+)"', source, re.M)
    # VR owns AA/TAA. The build name is metadata. r_enableRayTracing=0 crashes Windows
    # Steam 1.0.17.0 at first render; keep native device support (live A/B verified).
    # Resolution-derived LOD width and the scene far plane are overwritten natively; preserve them.
    excluded = {n for n, v in rows if n.lower().startswith('r_taa') or n in
                ('build_candidateName', 'r_antialiasing', 'r_multiSamples', 'r_enableRayTracing', 'r_lodModeWidth', 'r_zfar')}
    rows = [(n, v) for n, v in rows if n not in excluded]
    # Native render-use gate; unlike the device-support flag it can skip RT work
    # without withholding the resources the renderer's initialization expects.
    rows.append(('r_useRayTracing', '0'))
    profiles = json.loads((ROOT/'profiles/motor-builds.json').read_text())['profiles']
    binaries = [pathlib.Path(r'D:\Games\Jones\TheGreatCircle.exe'),
                pathlib.Path(r'D:\Games\dampf\steamapps\common\The Great Circle\TheGreatCircle.exe')]
    found = [resolve(p, profile['sha256'], dict(rows)) for p, profile in zip(binaries, profiles)]
    missing = [n for n, v in rows if any(n not in values for setter, values, mem in found)]
    assert missing == ['r_shadowSunCascadeMinMip'], 'Unexpected unresolved preset CVars: ' + repr(missing)
    rows = [(n, v) for n, v in rows if n not in missing]
    (ROOT/'profiles/low-performance-cvars.json').write_text(json.dumps([n for n,v in rows], indent=2)+'\n')
    catalog_path = ROOT/'profiles/motor-builds.json'
    catalog = json.loads(catalog_path.read_text())
    addresses = [(found[0][0], found[1][0], True)] + [(found[0][1][n], found[1][1][n], False) for n,v in rows]
    for gog, steam, code_flag in addresses:
        entry = dict(steam=hex(steam), code=code_flag,
                     gogBytes=found[0][2][gog:gog+32].hex(), steamBytes=found[1][2][steam:steam+32].hex())
        old = catalog['addresses'].get(hex(gog))
        assert not old or old == entry, 'Existing mapping differs: ' + hex(gog)
        catalog['addresses'][hex(gog)] = entry
    catalog_path.write_text(json.dumps(catalog, indent=2)+'\n')
    lines = ['// Generated by tools/generate-low-performance.py; ECLIPSE v1.0.12.0 preset.',
             '// Only registrations verified in the exact GOG/Steam 1.0.17.0 binaries are included.',
             '#pragma once', '#include <cstdint>', 'namespace circle::motor::low_performance {',
             'struct Setting { const char* name; const char* value; uintptr_t rva; };',
             'inline constexpr uintptr_t kSetter = ' + hex(found[0][0]) + ';',
             'inline constexpr Setting kSettings[] = {']
    lines += ['    {"%s", "%s", %s},' % (n, v, hex(found[0][1][n])) for n, v in rows]
    lines += ['};', '}']
    (ROOT/'src/motor/low_performance.generated.hpp').write_text('\n'.join(lines)+'\n')
    print('Resolved', len(rows), 'settings; setters', [hex(s) for s,v,m in found])
    print('VR-owned / metadata excluded:', ', '.join(sorted(excluded)))
    print('Removed in 1.0.17.0 (name absent from both binaries):', missing)

if __name__ == '__main__':
    main()

"""Generate the native build table from the launcher's exact-identity catalog."""
import argparse,json,hashlib
from pathlib import Path
ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');args=ap.parse_args()
root=Path(__file__).resolve().parent.parent
p=json.loads((root/'profiles/motor-builds.json').read_text())
lines=['// Generated by tools/generate-build-profiles.py; edit profiles/motor-builds.json.',
       '// Catalog SHA256: '+hashlib.sha256((root/'profiles/motor-builds.json').read_bytes()).hexdigest(),
       '#pragma once','#include "build_profile.hpp"','namespace circle::motor::build {','inline constexpr Profile profiles[] = {']
for x in p['profiles']:
    lines.append('    {Id::%s, "%s", "%s", %s, %s},'%(x['id'],x['name'],x['sha256'],x['timestamp'],x['imageSize']))
lines+=['};','struct Address { uintptr_t reference,steam; bool code; unsigned char gogBytes[32],steamBytes[32]; };','inline constexpr Address addresses[] = {']
def bytes_c(hexstr):
    b=bytes.fromhex(hexstr);assert len(b)==32
    return '{'+','.join('0x%02x'%n for n in b)+'}'
for key,x in sorted(p['addresses'].items(),key=lambda kv:int(kv[0],16)):
    lines.append('    {%s,%s,%s,%s,%s},'%(key,x['steam'],str(x['code']).lower(),bytes_c(x['gogBytes']),bytes_c(x['steamBytes'])))
lines+=['};','}',''];output='\n'.join(lines)
path=root/'src/motor/build_profiles.generated.hpp'
if args.check:
    assert path.read_text()==output,'Native and launcher build catalogs differ; regenerate.'
else:path.write_text(output)
print('Build profiles synchronized:',len(p['profiles']),'profiles,',len(p['addresses']),'addresses')
